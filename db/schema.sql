-- 1. FUNCIONES (Para Triggers)
-- Esta función actualiza la fecha de modificación automáticamente
CREATE OR REPLACE FUNCTION public.trigger_actualizar_last_update_date()
RETURNS TRIGGER AS $$
BEGIN
    NEW.last_update_date = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

