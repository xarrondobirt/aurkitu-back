-- Tipo enum para estados del objeto
CREATE TYPE public.estado_objeto AS ENUM (
    'perdido',
    'encontrado',
    'devuelto'
);

-- Tablas para usarios
CREATE TABLE public.usuario (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    username varchar(100) NOT NULL,
    hashed_password text NOT NULL,
    email varchar(100) NOT NULL,
    idioma_codigo varchar(5) NOT NULL DEFAULT 'es',
    verificado bool NOT NULL DEFAULT false,
    create_date timestamptz NOT NULL DEFAULT now(),
    last_update_date timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT usuario_pkey PRIMARY KEY (id),
    CONSTRAINT usuario_email_key UNIQUE (email),
    CONSTRAINT usuario_username_key UNIQUE (username)
);

-- Tabla para proceso de alta de usuario con códigos
CREATE TABLE public.codigos_verificacion (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NULL,
    code varchar(6) NOT NULL,
    create_date timestamptz NOT NULL DEFAULT now(),
    expiration_date timestamptz NOT NULL,
    CONSTRAINT codigos_verificacion_pkey PRIMARY KEY (id)
);

--Refresh tokens para JWT
CREATE TABLE public.refresh_token(
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    hashed_token varchar(255) NOT NULL,
    create_date timestamptz NOT NULL DEFAULT now(),
    expiration_date timestamptz NOT NULL,
    CONSTRAINT refresh_token_hashed_token_key UNIQUE (hashed_token),
    CONSTRAINT refresh_token_pkey PRIMARY KEY (id)
);

--Tabla de objetos
CREATE TABLE public.objeto(
    id bigint GENERATED BY DEFAULT AS IDENTITY, 
    estado public.estado_objeto NOT NULL DEFAULT 'perdido',   
    user_id bigint NOT NULL,
    ubicacion geography(Point, 4326) NOT NULL,
    radio_metros int NOT NULL DEFAULT 0,
    tipo int NOT NULL DEFAULT 0,
    descripcion text NOT NULL,
    marca text NULL,
    numero_serie text NULL,
    color int NOT NULL default 0,
    foto_url text NULL,
    factura_url text NULL,
    fecha_perdida timestamptz NOT NULL DEFAULT now(),
    create_date timestamptz NOT NULL DEFAULT now(),
    last_update_date timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT objeto_pkey PRIMARY KEY (id),
    CONSTRAINT objeto_descripcion_check CHECK (length(descripcion) > 0)    
);

-- Mensajes
CREATE TABLE public.mensaje (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    remitente_id bigint NOT NULL,
    destinatario_id bigint NOT NULL,
    objeto_id bigint NOT NULL,
    contenido text NOT NULL,
    leido BOOLEAN NOT NULL DEFAULT false,
    create_date timestamptz NOT NULL DEFAULT now(),
    last_update_date timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT mensaje_pkey PRIMARY KEY (id),
    CONSTRAINT mensaje_contenido_check CHECK (length(contenido) > 0)
);

