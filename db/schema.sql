-- Tirggers para la fecha de modificacion
CREATE TRIGGER trigger_usuario_modificacion
BEFORE UPDATE ON public.usuario
FOR EACH ROW EXECUTE FUNCTION public.trigger_actualizar_last_update_date();

CREATE TRIGGER trigger_objeto_modificacion
BEFORE UPDATE ON public.objeto
FOR EACH ROW EXECUTE FUNCTION public.trigger_actualizar_last_update_date();

CREATE TRIGGER trigger_mensaje_modificacion
BEFORE UPDATE ON public.mensaje
FOR EACH ROW EXECUTE FUNCTION public.trigger_actualizar_last_update_date();


-- INDICES - para las consultas de la funcionalidad mínima
CREATE INDEX codigos_verificacion_user_id_idx ON public.codigos_verificacion (user_id);
CREATE INDEX objeto_user_id_idx ON public.objeto (user_id);
CREATE INDEX objeto_ubicacion_gix ON public.objeto USING GiST (ubicacion);
CREATE INDEX mensaje_destinatario_id_idx ON public.mensaje (destinatario_id);
CREATE INDEX refresh_token_user_id_idx ON public.refresh_token (user_id);
